/**
 * Word data for Wordle: the 2315 curated answer words plus 12540 extra
 * accepted guesses (the original game's dictionary), stored as concatenated
 * uppercase blobs — one line per string constant keeps every literal far below
 * the class-file 64KB constant-pool limit.
 */
object WordleWords {

    val answers: List<String> by lazy { ANSWER_LINES.flatMap { it.chunked(5) } }

    private val validGuesses: Set<String> by lazy {
        buildSet {
            addAll(answers)
            GUESS_LINES.forEach { addAll(it.chunked(5)) }
        }
    }

    fun isValid(word: String): Boolean = word.length == 5 && word.uppercase() in validGuesses

    /**
     * The shared daily answer: a multiplicative hash of the UTC epoch day picks
     * from [answers], so every machine lands on the same word without a server.
     */
    fun answerForDay(epochDay: Long): String {
        val index = Math.floorMod(epochDay * 2654435761L, answers.size.toLong()).toInt()
        return answers[index]
    }

    fun todayEpochDay(): Long = LocalDate.now(java.time.ZoneOffset.UTC).toEpochDay()

    /** 1-based puzzle number, counted from the arcade's first Wordle day. */
    fun puzzleNumber(epochDay: Long): Long = (epochDay - FIRST_DAY + 1).coerceAtLeast(1)

